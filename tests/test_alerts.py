    def test_30_realistic_event_sequence(self, alert_engine: AlertEngine):
        """Test realistic sequence: breach -> alert -> ack -> loitering -> alert -> resolve all."""
        # 1. Fence breach occurs on Track 10
        fb = FenceBreachEvent(track_id=10, breach_count=1, frame_id=100, timestamp=10.0)
        a_fb = alert_engine.process_fence_breach(fb)
        assert a_fb is not None
        assert a_fb.is_active is True

        # 2. Operator acknowledges breach
        a_fb_ack = alert_engine.acknowledge(a_fb.alert_id, acknowledged_by="Duty Officer")
        assert a_fb_ack.is_acknowledged is True

        # 3. Loitering occurs on Track 15
        loiter = LoiteringEvent(track_id=15, loitering_count=1, duration_seconds=35.0, frame_id=200, timestamp=15.0)
        a_loiter = alert_engine.process_loitering(loiter)
        assert a_loiter is not None
        assert a_loiter.is_active is True

        # 4. Check active alerts
        active_unacked = alert_engine.get_active_alerts(include_acknowledged=False)
        assert len(active_unacked) == 1
        assert active_unacked[0].alert_id == a_loiter.alert_id

        active_all = alert_engine.get_active_alerts(include_acknowledged=True)
        assert len(active_all) == 2

        # 5. Resolve both
        alert_engine.resolve(a_fb.alert_id, resolved_by="Duty Officer")
        alert_engine.resolve(a_loiter.alert_id, resolved_by="Duty Officer")

        # 6. Verify zero active alerts remain
        assert alert_engine.count_active_alerts(include_acknowledged=True) == 0
        all_resolved = alert_engine.filter_alerts(status=AlertStatus.RESOLVED)
        assert len(all_resolved) == 2


