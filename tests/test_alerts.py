class TestLifecycleAndStateTransitions:
    """Tests 15, 16, 17, 18, 19, 20: Acknowledge, resolve, invalid transitions, reset."""

    def test_15_acknowledge_transition(self, alert_engine: AlertEngine):
        """Test transitioning ACTIVE -> ACKNOWLEDGED and recording metadata."""
        e1 = FenceBreachEvent(track_id=1, breach_count=1)
        alert = alert_engine.process_fence_breach(e1)

        ack_alert = alert_engine.acknowledge(alert.alert_id, acknowledged_by="Officer Sarah", timestamp=1234.5)
        assert ack_alert.status == AlertStatus.ACKNOWLEDGED
        assert ack_alert.acknowledged_by == "Officer Sarah"
        assert ack_alert.acknowledged_at == 1234.5
        assert ack_alert.is_acknowledged is True
        assert ack_alert.is_active is False

        # Verify state in engine matches
        stored = alert_engine.get_alert(alert.alert_id)
        assert stored.status == AlertStatus.ACKNOWLEDGED

    def test_16_resolve_transition(self, alert_engine: AlertEngine):
        """Test transitioning ACTIVE -> RESOLVED and ACKNOWLEDGED -> RESOLVED."""
        e1 = FenceBreachEvent(track_id=1, breach_count=1)
        e2 = LoiteringEvent(track_id=2, loitering_count=1)
        a1 = alert_engine.process_fence_breach(e1)
        a2 = alert_engine.process_loitering(e2)

        # Path 1: ACTIVE -> RESOLVED directly
        r1 = alert_engine.resolve(a1.alert_id, resolved_by="Officer John")
        assert r1.status == AlertStatus.RESOLVED
        assert r1.is_resolved is True
        assert r1.resolved_by == "Officer John"
        assert r1.resolved_at is not None

        # Path 2: ACTIVE -> ACKNOWLEDGED -> RESOLVED
        alert_engine.acknowledge(a2.alert_id, acknowledged_by="Officer John")
        r2 = alert_engine.resolve(a2.alert_id, resolved_by="Officer Mike")
        assert r2.status == AlertStatus.RESOLVED
        assert r2.acknowledged_by == "Officer John"
        assert r2.resolved_by == "Officer Mike"

    def test_17_invalid_state_transitions_raise_exception(self, alert_engine: AlertEngine):
        """Test that invalid backwards or terminal transitions raise InvalidAlertStateTransitionError."""
        e1 = FenceBreachEvent(track_id=1, breach_count=1)
        alert = alert_engine.process_fence_breach(e1)

        # ACKNOWLEDGED -> cannot re-acknowledge
        alert_engine.acknowledge(alert.alert_id)
        with pytest.raises(InvalidAlertStateTransitionError):
            alert_engine.acknowledge(alert.alert_id)

        # RESOLVED -> terminal state
        alert_engine.resolve(alert.alert_id)

        # Cannot resolve again
        with pytest.raises(InvalidAlertStateTransitionError):
            alert_engine.resolve(alert.alert_id)

        # Cannot acknowledge a resolved alert
        with pytest.raises(InvalidAlertStateTransitionError):
            alert_engine.acknowledge(alert.alert_id)

    def test_18_unknown_alert_id_raises_not_found(self, alert_engine: AlertEngine):
        """Test that operations on unknown alert ID raise AlertNotFoundError."""
        with pytest.raises(AlertNotFoundError):
            alert_engine.acknowledge("ALT-UNKNOWN")

        with pytest.raises(AlertNotFoundError):
            alert_engine.resolve("ALT-UNKNOWN")

    def test_19_and_20_reset_and_clear(self, alert_engine: AlertEngine):
        """Test reset and clear methods clear all alerts and deduplication memory."""
        e1 = FenceBreachEvent(track_id=1, breach_count=1)
        e2 = LoiteringEvent(track_id=2, loitering_count=1)
        alert_engine.process_fence_breach(e1)
        alert_engine.process_loitering(e2)
        assert len(alert_engine) == 2

        alert_engine.clear()
        assert len(alert_engine) == 0
        assert alert_engine.get_all_alerts() == []

        # After reset, the same event can be processed again
        a1_again = alert_engine.process_fence_breach(e1)
        assert a1_again is not None
        assert a1_again.alert_id == "ALT-00001"  # counter reset


